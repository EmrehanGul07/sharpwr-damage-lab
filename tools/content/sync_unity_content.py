"""Embed game content into the Unity package as C# string constants.

Embedding (instead of StreamingAssets/Resources) loads identically on desktop and Android and
keeps the Riot reference data in its own folder (Runtime/Reference) so a public build can drop it.
Usage: python -I tools/content/sync_unity_content.py [--check]
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PKG = ROOT / "game" / "packages" / "com.sharpwr.unity" / "Runtime"
OUTPUTS = {
    PKG / "Reference" / "EmbeddedReferenceContent.cs": (
        "EmbeddedReferenceContent",
        "Riot reference data (personal build only, ADR-0004 rev 2).",
        {"SamiraJson": "game/content/reference-riot/champions/samira.champion.json"},
    ),
    PKG / "Generated" / "EmbeddedContent.cs": (
        "EmbeddedContent",
        "Original SharpWR content.",
        {"DuelBotProfilesJson": "game/content/ai/duel-bot.profiles.json"},
    ),
}


def render(cls, doc, fields):
    lines = [
        "// <auto-generated> tools/content/sync_unity_content.py — do not edit. </auto-generated>",
        "namespace SharpWR.Unity",
        "{",
        f"    /// <summary>{doc}</summary>",
        f"    public static class {cls}",
        "    {",
    ]
    for name, rel in fields.items():
        text = (ROOT / rel).read_text(encoding="utf-8").replace('"', '""')
        lines.append(f"        /// <summary>{rel}</summary>")
        lines.append(f'        public const string {name} = @"{text}";')
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for path, (cls, doc, fields) in OUTPUTS.items():
        text = render(cls, doc, fields)
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale embedded content (run tools/content/sync_unity_content.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    if args.check:
        print("embedded content up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
